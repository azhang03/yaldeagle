/** The neckerchief: a white roll on top and a red cloth with a blue slide, at height y0. */
function kerchief(k: Kit, y0: number, z: number): void {
  k.box([0.38, 0.035, 0.03], [0, y0 + 0.02, z], '#f4f1ea');
  [0.36, 0.3, 0.24, 0.18, 0.12, 0.06].forEach((w, i) =>
    k.box([w, 0.05, 0.025], [0, y0 - 0.02 - i * 0.05, z], '#c8342f'),
  );
  k.box([0.08, 0.07, 0.05], [0, y0 - 0.02, z + 0.02], '#2d4f9e');
}

/** The drawing tube, upright, with its center at p. */
function tube(k: Kit, p: Vec3): void {
  k.cyl(0.07, 0.5, p, '#4b5563');
  k.cyl(0.076, 0.06, [p[0], p[1] + 0.25, p[2]], '#d14b3a');
  k.cyl(0.076, 0.03, [p[0], p[1] - 0.2, p[2]], '#d14b3a');
}

